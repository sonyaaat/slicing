/* Export the current table: LaTeX in the paper's star-grid format, CSV, or a link to this view.
 * Only attribute values and numbers leave the page, never conversation text. */
(function (root) {
  "use strict";
  const SL = root.SL;
  const { h, fmt, download, copyText } = SL.util;
  const { A } = SL.data;
  const dat = SL.data;
  let R = null;

  function rowsOf(st, res) {
    return res.worse.concat(res.better);
  }

  function latex(st, res) {
    const sc = res.scope;
    const rows = rowsOf(st, res);
    const used = [...new Set(rows.flatMap((r) => r.conds.map(([c]) => c)))].sort((a, b) => A[a].order - A[b].order);
    const fam = sc.family;
    const tex = (s) => String(s).replace(/([&%$#_{}])/g, "\\$1").replace(/–/g, "--");
    const num = (x) => (x < 0 ? `$-${Math.abs(x).toFixed(2)}$` : x.toFixed(2));
    const mean = (m, idx) => dat.meanIdx(dat.localNum(sc, `${fam}_${m}`), idx)[0];
    const all = Int32Array.from({ length: sc.n }, (_, i) => i);
    const head = used.map((c) => tex(A[c].short + (A[c].group === "theme" ? "$^\\dagger$" : ""))).concat(["$n$", "GPT", "Claude", "Dev."]);
    const line = (cells) => "  " + cells.join(" & ") + " \\\\";
    const out = [];
    out.push("% Generated by the Sliceability demo. Needs \\usepackage{booktabs}.");
    out.push(`% Scope: ${sc.name}; target ${fam}_${st.target}; min support ${st.sup}; min effect ${st.eff}; max ${st.conj} conditions; ${res.rows.length} rows.`);
    out.push(`% GPT / Claude: mean ${fam === "score_rel" ? "score minus theme mean" : "score"} in the slice; Dev.: difference of the ${st.target === "mean" ? "two-model mean" : st.target} score as a share of the scope mean.`);
    out.push("\\begin{table*}[t]", "\\centering", "\\small", `\\begin{tabular}{${"l".repeat(used.length)}rrrr}`, "\\toprule");
    out.push(line(head), "\\midrule");
    out.push(line(used.map(() => "*").concat([String(sc.n), num(mean("gpt", all)), num(mean("claude", all)), ""])));
    for (const r of rows) {
      const cells = used.map((c) => { const k = r.conds.find(([cc]) => cc === c); return k ? tex(dat.label(c, k[1])) : "*"; });
      const pct = Math.round(100 * r.pctT);
      cells.push(String(r.n), num(mean("gpt", r.idx)), num(mean("claude", r.idx)), pct < 0 ? `$-${Math.abs(pct)}\\%$` : `$+${pct}\\%$`);
      out.push(line(cells));
    }
    out.push("\\bottomrule", "\\end{tabular}");
    out.push(`\\caption{Explanation table on ${tex(sc.name)} (${sc.n} conversations).${used.some((c) => A[c].group === "theme") ? " $^\\dagger$: attribute discovered inside the theme." : ""}}`);
    out.push("\\end{table*}");
    return out.join("\n");
  }

  function csv(st, res) {
    const rows = rowsOf(st, res);
    const q = (s) => `"${String(s).replace(/"/g, '""')}"`;
    const head = ["order", "pick_step", "conditions", "rule_columns", "n", "share", "gpt_dev_pts", "claude_dev_pts", "target",
      "target_dev_pts", "target_dev_pct", "gpt_mean_score", "claude_mean_score"];
    const lines = [head.join(",")];
    rows.forEach((r, i) => lines.push([i + 1, r.step, q(r.conds.map(([c, v]) => `${A[c].name}: ${dat.label(c, v)}`).join(" AND ")),
      q(r.conds.map(([c, v]) => `${c}=${v}`).join(" AND ")), r.n, r.share.toFixed(4), (100 * r.dev.gpt).toFixed(2), (100 * r.dev.claude).toFixed(2),
      `${res.scope.family}_${st.target}`, (100 * r.devT).toFixed(2), (100 * r.pctT).toFixed(1), r.abs.gpt.toFixed(4), r.abs.claude.toFixed(4)].join(",")));
    return lines.join("\n") + "\n";
  }

  function open() {
    close();
    const st = SL.state.get();
    const res = SL.model.search(st);
    const ta = h("textarea", { class: "code", readonly: true, spellcheck: "false" });
    ta.value = latex(st, res);
    const msg = h("span", { class: "faint small" });
    const body = h("div", { class: "modal-b" },
      h("p", { class: "card-sub" }, "The table as shown, in the star-grid format of the paper. Attribute values and numbers only; no conversation text."),
      ta,
      h("div", { style: { display: "flex", gap: "8px", marginTop: "10px", alignItems: "center", flexWrap: "wrap" } },
        h("button", { class: "btn primary", onclick: async () => { msg.textContent = (await copyText(ta.value)) ? "LaTeX copied." : "Copy failed: select the text and copy it."; } }, "Copy LaTeX"),
        h("button", { class: "btn", onclick: () => download(`slices_${res.scope.key}_${st.target}.csv`, csv(st, res), "text/csv") }, "Download CSV"),
        h("button", { class: "btn", onclick: async () => { msg.textContent = (await copyText(location.href)) ? "Link to this exact view copied." : location.href; } }, "Copy link to this view"),
        msg));
    const md = h("div", { class: "modal", role: "dialog", "aria-label": "Export" },
      h("div", { class: "sheet-h" }, h("div", { class: "grow" }, h("h3", { class: "card-title" }, "Export the table")),
        h("button", { class: "xbtn", "aria-label": "Close", onclick: close }, "×")), body);
    const ov = h("div", { class: "overlay", onclick: (e) => { if (e.target === ov) close(); } }, md);
    R = ov;
    document.getElementById("overlay-root").append(ov);
    document.addEventListener("keydown", onKey);
  }
  function onKey(e) { if (e.key === "Escape") close(); }
  function close() { if (R) R.remove(); R = null; document.removeEventListener("keydown", onKey); }

  SL.views = SL.views || {};
  SL.views.exportView = { open, close, latex, csv };
})(window);
